"""Writes the docs' Reference pages from honest-agent itself, so they can't drift from it.

- reference/cli.md: every command and option, from the Click definitions (`--help`).
- reference/config.md: every setting in honest_agent_config.yml. The setting names come
  from config_file.py; their descriptions live below, and the script stops if the two
  disagree, so a new setting can't go undocumented.

Run it from the repository root after changing the CLI or the config:

    uv run --directory cli python ../site/scripts/generate_reference.py
"""

from __future__ import annotations

from pathlib import Path

import click

from honest_agent import config_file
from honest_agent.cli import DEFAULT_MAX_TOOL_STEPS, DEFAULT_RESULTS_PATH, main

OUT = Path(__file__).resolve().parents[1] / "src/content/docs/docs/reference"
GENERATED = "<!-- Generated by site/scripts/generate_reference.py: edit that script, not this file. -->"

# Each setting: (where it can go, what it does). Where: "top" (top level only),
# "both" (top level, or per target) or "target" (per target only).
SETTINGS = {
    "default_target": ("top", "The target `run`, `debug`, `ls` and `notify` use without `--target`."),
    "targets": ("top", "One entry per agent you evaluate, by name. Each holds the target settings below."),
    "results_path": (
        "top",
        f"Where results are stored: a local DuckDB file (default `{DEFAULT_RESULTS_PATH}`) or a MotherDuck "
        "database as `md:<name>`. To keep the file in cloud storage such as S3, copy it in and out around each "
        "run ([Storing results](/docs/storing-results/#in-cloud-storage)). Every target shares it, so one report "
        "covers every agent.",
    ),
    "model": ("both", "The model that plays the agent. Default: chosen from the API key you have."),
    "grading_model": (
        "both",
        "The model for grading: it pulls the value out for `extract_match` and judges the answer for "
        "`llm_judge` (`contains` uses none). Default: `model`.",
    ),
    "max_tool_steps": (
        "both",
        f"Steps the agent may take per question; a step is one model call and the tool calls it asks for. "
        f"Default: {DEFAULT_MAX_TOOL_STEPS}.",
    ),
    "mcp_url": ("target", "The URL of a remote MCP server. Set this or `mcp_command`."),
    "mcp_command": ("target", "The command that starts a local MCP server. Set this or `mcp_url`."),
    "bearer_token_env": ("target", "The name of the variable that holds the server's bearer token, never the token."),
    "mcp_env": (
        "target",
        "Variables from `.env` a local server needs. It gets only these, plus `PATH`, `HOME` and similar.",
    ),
    "evals_dir": ("target", "The folder with this target's evals. Default: `evals`."),
    "agent_name": ("target", "The name results are recorded under. Default: the target's name."),
    "default_database": ("target", "The database where the server runs a bare table name, for provenance."),
    "default_schema": ("target", "The schema where the server runs a bare table name, for provenance."),
    "ignore_tools": (
        "target",
        "Tools whose `sql`, `query` or `statement` argument isn't SQL, so provenance skips them.",
    ),
}


def _cell(text: str) -> str:
    """Help text on one line, with `|` escaped and `<` kept as text outside code spans
    (inside backticks Markdown already shows it as is)."""
    parts = " ".join(text.split()).split("`")
    return "`".join(part if i % 2 else part.replace("|", "\\|").replace("<", "&lt;") for i, part in enumerate(parts))


def _default(param: click.Parameter) -> str:
    default = param.default
    if callable(default) or default is None or repr(default).endswith("UNSET") or param.multiple and not default:
        return ""
    if isinstance(param, click.Option) and param.is_flag:
        if not param.secondary_opts:
            return ""
        return f"`{param.opts[0] if default else param.secondary_opts[0]}`"
    return f"`{default}`"


def _option_name(param: click.Option, command: click.Command) -> str:
    """The option as `--help` writes it, e.g. `-t, --target TEXT`."""
    record = param.get_help_record(click.Context(command))
    return f"`{record[0]}`" if record else ""


def _options_list(command: click.Command) -> list[str]:
    """One list item per option: its name as `--help` writes it, what it does, and its
    environment variable and default when it has them."""
    lines = []
    for p in command.params:
        if not isinstance(p, click.Option) or p.hidden:
            continue
        extras = []
        if isinstance(p.envvar, str):
            extras.append(f"environment variable `{p.envvar}`")
        if default := _default(p):
            extras.append(f"default {default}")
        line = f"- **{_option_name(p, command)}**: {_cell(p.help or '')}"
        if extras:
            line += f" *({'; '.join(extras)})*"
        lines.append(line)
    return lines


def cli_page() -> str:
    lines = [
        "---",
        "title: CLI commands",
        "description: Every honest-agent command and option.",
        "---",
        "",
        GENERATED,
        "",
        "Run any command with `--help` to see the same in your terminal. A flag beats an environment "
        "variable, which beats `honest_agent_config.yml`, which beats the default.",
        "",
        "## Options for every command",
        "",
        "These go before the command, like `honest-agent --env-file prod.env run`.",
        "",
        *_options_list(main),
    ]
    for name, command in sorted(main.commands.items()):
        lines += ["", f"## `{name}`", "", _cell(command.help or ""), ""]
        lines += [f"```bash\nhonest-agent {name} [OPTIONS]\n```", ""]
        lines += _options_list(command)
    return "\n".join(lines) + "\n"


def config_page() -> str:
    documented = set(SETTINGS)
    known = config_file._TOP_LEVEL_KEYS | config_file._TARGET_KEYS
    if documented != known:
        raise SystemExit(
            f"SETTINGS and config_file.py disagree. Undocumented: {sorted(known - documented)}; "
            f"unknown: {sorted(documented - known)}."
        )
    for key, (where, _) in SETTINGS.items():
        actual = (
            "both" if key in config_file._SHARED_KEYS else "top" if key in config_file._TOP_LEVEL_KEYS else "target"
        )
        if where != actual:
            raise SystemExit(f"SETTINGS says {key} goes at {where!r}, but config_file.py says {actual!r}.")

    def table(where: str) -> list[str]:
        rows = ["| Setting | What it does |", "|---|---|"]
        rows += [f"| `{key}` | {_cell(text)} |" for key, (w, text) in sorted(SETTINGS.items()) if w == where]
        return rows

    lines = [
        "---",
        "title: Config keys",
        "description: Every setting in honest_agent_config.yml.",
        "---",
        "",
        GENERATED,
        "",
        "`honest_agent_config.yml` holds a project's settings, with one target per agent. Any value can "
        "read an environment variable with `{{ env_var('NAME') }}` or `{{ env_var('NAME', 'default') }}`. "
        "Relative paths are relative to the file's folder. [Connect your agent](/docs/connect/) explains "
        "them with examples.",
        "",
        "```yaml",
        "results_path: ./honest_agent_results/results.duckdb",
        "model: claude-sonnet-4-5            # top level: for every target",
        "default_target: sales-agent",
        "",
        "targets:",
        "  sales-agent:",
        "    mcp_url: \"{{ env_var('SALES_AGENT_MCP_URL') }}\"",
        "    bearer_token_env: SALES_AGENT_MCP_TOKEN",
        "    max_tool_steps: 8               # per target: only this one",
        "```",
        "",
        "## Top level only",
        "",
        *table("top"),
        "",
        "## Top level or per target",
        "",
        "Set at the top level, a value applies to every target; a target's own value wins.",
        "",
        *table("both"),
        "",
        "## Per target",
        "",
        *table("target"),
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "cli.md").write_text(cli_page())
    (OUT / "config.md").write_text(config_page())
    print(f"Wrote {OUT / 'cli.md'} and {OUT / 'config.md'}")
